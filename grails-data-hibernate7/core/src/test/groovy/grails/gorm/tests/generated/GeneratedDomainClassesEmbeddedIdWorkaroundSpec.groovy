package grails.gorm.tests.generated

import java.sql.Connection
import java.sql.ResultSet
import java.sql.Statement
import java.util.concurrent.atomic.AtomicInteger

import grails.persistence.Entity
import org.hibernate.engine.jdbc.connections.spi.ConnectionProvider
import org.hibernate.engine.spi.SessionFactoryImplementor
import spock.lang.Specification

import org.grails.orm.hibernate.HibernateDatastore

/**
 * The supported way to move an embedded object that is a part of a composite identifier (<code>id composite: ['code',
 * 'address']</code> with <code>address</code> in <code>static embedded</code>), which the classic binding of Grails 8 accepted and
 * native binding refuses: the properties of the embedded class become plain properties of the identifier. The spec proves, through
 * the public datastore API, that the flattened entity keeps the schema the embedded one had (recorded from Grails 8 in
 * {@link #EMBEDDED_SCHEMA}: tables, columns, primary key columns and their order, foreign keys of a many-to-one and of a hasMany, as H2
 * states them), that rows the embedded entity wrote stay readable, and that a transient accessor keeps <code>customer.address</code>
 * compiling.
 */
class GeneratedDomainClassesEmbeddedIdWorkaroundSpec extends Specification {

    private static final AtomicInteger BOOTS = new AtomicInteger()

    private static final String CUSTOMER_PRIMARY_KEY =
            'ALTER TABLE "PUBLIC"."EID_CUSTOMER" ADD CONSTRAINT "PUBLIC"."CONSTRAINT_#" PRIMARY KEY("ADDRESS_CITY", "ADDRESS_STREET", "CODE");'

    /** The H2 script of the schema the classic binding of Grails 8 created for the embedded version, as {@link #script} reads it. */
    private static final List<String> EMBEDDED_SCHEMA = [
            CUSTOMER_PRIMARY_KEY,
            'ALTER TABLE "PUBLIC"."EID_CUSTOMER" ADD CONSTRAINT "PUBLIC"."FKTENTYQNKSHX2SUF9F5R2X3UYS" FOREIGN KEY("REGION_ID") REFERENCES "PUBLIC"."EID_REGION"("ID") NOCHECK;',
            'ALTER TABLE "PUBLIC"."EID_REGION" ADD CONSTRAINT "PUBLIC"."CONSTRAINT_#" PRIMARY KEY("ID");',
            'CREATE MEMORY TABLE "PUBLIC"."EID_CUSTOMER"(\n    "REGION_ID" BIGINT,\n    "VERSION" BIGINT NOT NULL,\n    "ADDRESS_CITY" CHARACTER VARYING(255) NOT NULL,\n' +
                    '    "ADDRESS_STREET" CHARACTER VARYING(255) NOT NULL,\n    "CODE" CHARACTER VARYING(255) NOT NULL,\n    "NAME" CHARACTER VARYING(255)\n);',
            'CREATE MEMORY TABLE "PUBLIC"."EID_REGION"(\n    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1) NOT NULL,\n    "VERSION" BIGINT NOT NULL,\n' +
                    '    "NAME" CHARACTER VARYING(255)\n);',
    ].asImmutable()

    private static final List<Class> EMBEDDED = [EidEmbCustomer, EidEmbRegion]
    private static final List<Class> FLATTENED = [EidFlatCustomer, EidFlatRegion]
    private static final List<Class> WITH_ACCESSOR = [EidAccessorCustomer, EidAccessorRegion]

    private static Map<String, Object> config(String url, String dbCreate = 'create-drop') {
        return [
                'dataSource.url'     : url,
                'dataSource.dbCreate': dbCreate,
        ]
    }

    private static String freshUrl() {
        return "jdbc:h2:mem:eidWorkaround${BOOTS.incrementAndGet()};LOCK_TIMEOUT=10000".toString()
    }

    /** The schema H2 holds after the boot, as its own script without data, in a stable order and without generated names. */
    private static List<String> schema(List<Class> classes) {
        HibernateDatastore datastore = new HibernateDatastore(config(freshUrl()), classes as Class[])
        try {
            return script(datastore)
        } finally {
            datastore.close()
        }
    }

    private static List<String> script(HibernateDatastore datastore) {
        ConnectionProvider provider = ((SessionFactoryImplementor) datastore.sessionFactory).serviceRegistry.getService(ConnectionProvider)
        Connection connection = provider.connection
        try {
            Statement statement = connection.createStatement()
            ResultSet rows = statement.executeQuery('SCRIPT NODATA')
            List<String> statements = []
            while (rows.next()) {
                String line = rows.getString(1)
                if (!line.startsWith('--') && !line.startsWith('CREATE USER')) {
                    statements << line.replaceAll(/(?i)\b(CONSTRAINT|PRIMARY_KEY|CONSTRAINT_INDEX)_[0-9A-F]+\b/, '$1_#').trim()
                }
            }
            return statements.sort(false)
        } finally {
            provider.closeConnection(connection)
        }
    }

    private static String purchaseKey(List<String> script) {
        return script.find { String statement -> statement.contains('"EID_PURCHASE"') && statement.contains('FOREIGN KEY') }
    }

    def "an embedded object as a part of the identifier is replaced by its properties, with the schema unchanged"() {
        expect: 'the embedded entity created the primary key over the columns of the embedded properties, in this order'
        EMBEDDED_SCHEMA.contains(CUSTOMER_PRIMARY_KEY)
        EMBEDDED_SCHEMA.any { it.contains('"ADDRESS_CITY" CHARACTER VARYING(255) NOT NULL') }

        and: 'the flattened entity creates every table, column, key and constraint the same'
        schema(FLATTENED) == EMBEDDED_SCHEMA
    }

    def "native binding refuses the embedded version and points at the flattened one"() {
        when:
        schema(EMBEDDED)

        then:
        RuntimeException failure = thrown()
        failure.toString().contains('Composite identifier part [address] of [grails.gorm.tests.generated.EidEmbCustomer] is an embedded object')
        failure.toString().contains('Map the properties of the embedded class as plain properties of the identifier')
        failure.toString().contains('Native Domain Binding chapter')
    }

    def "a transient accessor keeps the schema and adds no column"() {
        expect:
        schema(WITH_ACCESSOR) == EMBEDDED_SCHEMA
    }

    def "a many-to-one to the flattened entity references the identifier columns in the identifier order, as with classic binding"() {
        given:
        List<String> script = schema(FLATTENED + EidFlatPurchase)

        expect:
        script.containsAll(EMBEDDED_SCHEMA)
        purchaseKey(script) ==
                'ALTER TABLE "PUBLIC"."EID_PURCHASE" ADD CONSTRAINT "PUBLIC"."FKRBA3TSBPYXEJHWMBNOVA4F9VV" FOREIGN KEY' +
                '("EID_CUSTOMER_ADDRESS_CITY", "EID_CUSTOMER_ADDRESS_STREET", "EID_CUSTOMER_CODE") REFERENCES ' +
                '"PUBLIC"."EID_CUSTOMER"("ADDRESS_CITY", "ADDRESS_STREET", "CODE") NOCHECK;'
        script.any { it.contains('"EID_CUSTOMER_ADDRESS_CITY" CHARACTER VARYING(255),') }
    }

    def "a hasMany bound through a join table to a composite identifier is refused (classic binding could not boot it either)"() {
        when:
        schema([EidFlatCustomer, EidFlatRegion, EidFlatTeam])

        then:
        RuntimeException failure = thrown()
        failure.toString().contains('the collection is bound through a join table')
    }

    private static void shutdown(String url) {
        Connection connection = java.sql.DriverManager.getConnection(url)
        try {
            connection.createStatement().execute('SHUTDOWN')
        } finally {
            connection.close()
        }
    }

    private static String existingDatabase() {
        return "jdbc:h2:mem:eidExisting${BOOTS.incrementAndGet()};DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=10000".toString()
    }

    /**
     * The database of an application of Grails 8 that used the embedded version: its schema ({@link #EMBEDDED_SCHEMA}, the primary
     * key constraints told apart by name) and the rows the embedded entity wrote.
     */
    private static void writeEmbedded(String url) {
        Connection connection = java.sql.DriverManager.getConnection(url)
        try {
            Statement statement = connection.createStatement()
            int constraints = 0
            EMBEDDED_SCHEMA.findAll { it.startsWith('CREATE') }.each { String ddl -> statement.execute(ddl) }
            EMBEDDED_SCHEMA.findAll { it.startsWith('ALTER') }.sort { String ddl -> ddl.contains('PRIMARY KEY') ? 0 : 1 }.each { String ddl ->
                statement.execute(ddl.replace('"CONSTRAINT_#"', "\"CONSTRAINT_${++constraints}\"".toString()))
            }
            statement.execute("insert into eid_region (id, version, name) values (1, 0, 'eu')")
            statement.execute("insert into eid_customer (region_id, version, address_city, address_street, code, name) values (1, 0, 'x1', 's1', 'c1', 'one')")
            statement.execute("insert into eid_customer (region_id, version, address_city, address_street, code, name) values (1, 0, 'x2', 's2', 'c2', 'two')")
        } finally {
            connection.close()
        }
    }

    private static List<List> rows(String url, String sql) {
        Connection connection = java.sql.DriverManager.getConnection(url)
        try {
            ResultSet result = connection.createStatement().executeQuery(sql)
            List<List> found = []
            while (result.next()) {
                found << (1..result.metaData.columnCount).collect { int i -> result.getObject(i) }
            }
            return found
        } finally {
            connection.close()
        }
    }

    def "rows the embedded entity wrote stay readable and writable through the flattened entity, on the same database"() {
        given:
        String url = existingDatabase()
        writeEmbedded(url)
        HibernateDatastore datastore = new HibernateDatastore(config(url, 'validate'), FLATTENED as Class[])
        Map found = [:]

        when:
        EidFlatCustomer.withTransaction {
            found.byKey = EidFlatCustomer.get(new EidFlatCustomer(code: 'c1', addressStreet: 's1', addressCity: 'x1'))?.name
            found.missing = EidFlatCustomer.get(new EidFlatCustomer(code: 'c1', addressStreet: 's2', addressCity: 'x1'))
            found.byFinder = EidFlatCustomer.findByAddressStreetAndAddressCity('s2', 'x2')?.name
            found.byWhere = EidFlatCustomer.where { addressCity == 'x1' }.list()*.code
            found.count = EidFlatCustomer.count()
            found.region = EidFlatRegion.list().first().customers*.name.sort()
            found.customerRegion = EidFlatCustomer.findByCode('c2').region.name
        }
        EidFlatCustomer.withTransaction {
            EidFlatCustomer one = EidFlatCustomer.get(new EidFlatCustomer(code: 'c1', addressStreet: 's1', addressCity: 'x1'))
            one.name = 'uno'
            one.save(failOnError: true)
            new EidFlatCustomer(code: 'c3', addressStreet: 's3', addressCity: 'x3', name: 'three', region: one.region)
                    .save(failOnError: true, flush: true)
        }
        EidFlatCustomer.withTransaction {
            found.updated = EidFlatCustomer.get(new EidFlatCustomer(code: 'c1', addressStreet: 's1', addressCity: 'x1')).name
            found.total = EidFlatCustomer.count()
            found.region3 = EidFlatRegion.list().first().customers*.code.sort()
        }
        datastore.close()
        found.back = rows(url, "select name from eid_customer where code = 'c3' and address_street = 's3' and address_city = 'x3'")
        found.backCount = rows(url, 'select count(*) from eid_customer')

        then: 'the rows are read, and the ones written are in the columns the embedded entity used'
        found == [byKey: 'one', missing: null, byFinder: 'two', byWhere: ['c1'], count: 2, region: ['one', 'two'], customerRegion: 'eu',
                  updated: 'uno', total: 3, region3: ['c1', 'c2', 'c3'], back: [['three']], backCount: [[3L]]]

        cleanup:
        shutdown(url)
    }

    def "the transient accessor rebuilds the embedded object from the rows the embedded entity wrote, and is not persisted"() {
        given:
        String url = existingDatabase()
        writeEmbedded(url)
        HibernateDatastore datastore = new HibernateDatastore(config(url, 'validate'), WITH_ACCESSOR as Class[])
        Map found = [:]

        when:
        EidAccessorCustomer.withTransaction {
            EidAccessorCustomer one = EidAccessorCustomer.get(new EidAccessorCustomer(address: new EidAddress(street: 's1', city: 'x1'), code: 'c1'))
            found.name = one.name
            found.address = [one.address.street, one.address.city]
            new EidAccessorCustomer(code: 'c9', address: new EidAddress(street: 'nine', city: 'xn'), name: 'nine').save(failOnError: true, flush: true)
        }
        EidAccessorCustomer.withTransaction {
            EidAccessorCustomer nine = EidAccessorCustomer.findByAddressStreet('nine')
            found.saved = [nine.addressStreet, nine.addressCity, nine.address.city]
            found.persistent = datastore.mappingContext.getPersistentEntity(EidAccessorCustomer.name).persistentProperties*.name.contains('address')
        }

        then:
        found == [name: 'one', address: ['s1', 'x1'], saved: ['nine', 'xn', 'xn'], persistent: false]

        cleanup:
        datastore?.close()
        shutdown(url)
    }
}


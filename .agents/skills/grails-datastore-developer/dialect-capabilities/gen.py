"""Renders dialect-capabilities.md from the TSV that Dump.java wrote (see regen.sh)."""
import collections, sys

CURATED = [
    # (capability, what a change depends on when it relies on it)
    ('supportsEmptyInList', 'an empty IN () is legal SQL (H5 reports it; H7 renders the empty list itself)'),
    ('getInExpressionCountLimit', 'IN-list size; 0 = unlimited. An empty IN () is a separate question, see the note below'),
    ('getNullOrdering', 'where nulls sort by default'),
    ('supportsNullPrecedence', 'nulls first / nulls last accepted in ORDER BY'),
    ('toBooleanValueString(true)', 'boolean literal'),
    ('isEmptyStringTreatedAsNull', "'' is NULL (Oracle): unique and not-null checks differ"),
    ('supportsCaseInsensitiveLike', 'native ilike'),
    ('getCaseInsensitiveLike', 'ilike spelling'),
    ('supportsOrderByInSubquery', 'order by inside a subquery'),
    ('supportsOffsetInSubquery', 'offset or limit inside a subquery'),
    ('supportsRowValueConstructorSyntaxInInList', '(a, b) in ((..), (..))'),
    ('supportsTupleCounts', 'count((a, b))'),
    ('supportsSubqueryInSelect', 'a subquery in the select list'),
    ('supportsNestedSubqueryCorrelation', 'a correlated subquery inside a subquery'),
    ('supportsUnionAll', 'union all'),
    ('supportsOrdinalSelectItemReference', 'order by 1'),
    ('requiresCastForConcatenatingNonStrings', 'concat of a number needs a cast'),
    ('getMaxIdentifierLength', 'longest table / column / alias name'),
    ('getParameterCountLimit', 'bind parameters per statement; 0 = unlimited'),
    ('supportsLockTimeouts', 'lock timeouts'),
    ('getNativeIdentifierGeneratorStrategy', 'identity versus sequence'),
]

def load(path):
    rows = collections.defaultdict(dict); classes = {}
    for line in open(path):
        v, d, k, val = line.rstrip('\n').split('\t', 3)
        if k == '(class)': classes[d] = val
        else: rows[d][k] = val
    return v, rows, classes

def table(rows, classes, caps):
    dialects = [d for d in rows]
    out = ['| capability | ' + ' | '.join(dialects) + ' | relied on when |', '|---|' + '---|' * (len(dialects) + 1)]
    for cap, why in caps:
        vals = [rows[d].get(cap, 'n/a') for d in dialects]
        mark = ' **not reported**' if set(vals) == {'n/a'} else ('' if len(set(vals)) == 1 else ' **differs**')
        out.append(f'| `{cap}`{mark} | ' + ' | '.join(vals) + f' | {why} |')
    return '\n'.join(out)

def main():
    parts = ['<!--', 'SPDX-License-Identifier: Apache-2.0', '', 'Licensed to the Apache Software Foundation (ASF) under one or more contributor license agreements; and to You under the Apache License, Version 2.0.', '-->', '', '# Dialect capabilities', '',
             'Generated by `.agents/skills/grails-datastore-developer/dialect-capabilities/regen.sh` from the `Dialect` classes of the Hibernate jars each branch ships.',
             'Do not edit the tables by hand: regenerate. A default-constructed dialect reports the default database version, not every version.',
             'Source of every cell: **Dialect API**. No cell is verified on a container; the table says what Hibernate reports, not what a database does.', '',
             '## How to use it', '',
             '1. List the capabilities your change relies on (SQL text, literals, IN lists, null order, pagination, concat, identifiers, locks).',
             '2. Look each one up below. If every dialect has the same reported value, the change is dialect-independent for that capability: no container run. A row marked **not reported** (every cell `n/a`) means that this Hibernate version has no such method; it says nothing about the databases and is not agreement. Look the capability up in the other Hibernate table, and if no table reports it, treat it as dialect-dependent. Null ordering is the example: Hibernate 5 reports no `getNullOrdering`, and Hibernate 7 shows that the databases differ.',
             '3. If the values differ, the dialects that differ need a Testcontainers run, or the PR says why the difference cannot matter.',
             '4. A change that relies on nothing in the table because it builds JPA predicates and never renders SQL is independent; say so in the PR.', '',
             '**Empty IN list.** Hibernate 5 reports it as `supportsEmptyInList`; Hibernate 7 has no such method and renders an empty list itself, so a change that can emit one is dialect-dependent on H7 until a container run says otherwise.', '']
    for path in sys.argv[1:]:
        v, rows, classes = load(path)
        parts += [f'## {v}', '', 'Dialect class used: ' + ', '.join(f'{d}={c}' for d, c in classes.items()), '', table({d: r for d, r in rows.items()}, classes, CURATED), '']
        diff = [k for k in sorted({k for r in rows.values() for k in r}) if len({r.get(k, 'n/a') for r in rows.values()}) > 1]
        parts += [f'<details><summary>All {len(diff)} capabilities that differ between these dialects</summary>', '', '`' + '`, `'.join(diff) + '`', '', '</details>', '']
    print('\n'.join(parts))
main()

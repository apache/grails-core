package org.apache.grails.forge.core.change

import groovy.transform.CompileStatic

/**
 * A generated project cannot be changed as it was asked. The message is one line that says why and,
 * where there is something to do about it, what; it names files by their paths in the project.
 *
 * @since 9.0
 */
@CompileStatic
class ProjectChangeException extends RuntimeException {

    /** The record of the application was written by {@code project migrate}, for an application the generator did not make: there is no baseline. */
    public static final String UNTRACKED_RECORD = 'untracked-record'

    /** The application was generated by another version of the generator, or for another version of Grails. */
    public static final String OTHER_GENERATOR = 'other-generator'

    /** The application has a feature of a feature pack that is not part of Grails. */
    public static final String PACK_FEATURES = 'pack-features'

    /** An earlier change of the project was interrupted and has to be ended first. */
    public static final String INTERRUPTED_CHANGE = 'interrupted-change'

    /** The generator fails to generate the application again from its record. */
    public static final String NOT_REGENERABLE = 'not-regenerable'

    /** The application generated again from its record does not give the files of the baseline. */
    public static final String BASELINE_DIFFERS = 'baseline-differs'

    /** The application generated again from its record does not give the record itself: the manifest, the lock or the index of the baseline. */
    public static final String RECORD_DIFFERS = 'record-differs'

    /** A file of the project cannot be read. */
    public static final String UNREADABLE_FILE = 'unreadable-file'

    private final String reason

    ProjectChangeException(String message) {
        super(message)
        this.reason = null
    }

    ProjectChangeException(String message, Throwable cause) {
        super(message, cause)
        this.reason = null
    }

    /**
     * @param reason why, as one of the codes of this class
     * @param cause what was thrown, or {@code null}
     */
    ProjectChangeException(String message, String reason, Throwable cause) {
        super(message, cause)
        this.reason = reason
    }

    /**
     * @return why the project cannot be changed or generated again, as one of the codes of this class,
     * which stay the same from one version to the next; {@code null} for any other reason, as when a
     * file of a change cannot be written
     */
    String getReason() {
        return reason
    }
}

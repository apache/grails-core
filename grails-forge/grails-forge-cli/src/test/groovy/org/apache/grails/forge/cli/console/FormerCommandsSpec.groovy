    void "every command the Grails shell and its profiles had, as the record of them has it, is a command here or is in the table"() {
        given: 'the record of the commands of Grails 8, written from the sources of the shell and of the profiles before they were removed'
        List<List<String>> recorded = getClass().getResourceAsStream(RECORD).readLines('UTF-8')
                .findAll { !it.startsWith('#') }
                .collect { it.split('\t', -1) as List<String> }
        // the commands of the shell itself, and what its interactive mode took besides commands
        Set<String> ofShell = recorded.findAll { it[1] in ['shell', 'shell-interactive'] }*.first() as Set
        // the commands of the profiles: one for each file, and the other names a script gave itself
        Set<String> ofProfiles = recorded.findAll { it[1].startsWith('profile:') }*.first() as Set

        and: 'a project of each kind, and the directory above them'
        PROJECTS.each { String kind, List<String> create -> commandsIn(create) }
        Closure<Boolean> isCommand = { String kind, String name ->
            System.setProperty('user.dir', (kind == 'outside' ? top : new File(top, PROJECTS[kind][1].substring('example.'.length()))).absolutePath)
            out.reset()
            err.reset()
            // by its name, another name it has, or as what is short for one command
            ForgeCli.execute(beanContext, 'help', name) == 0
        }

        expect: 'the record is whole: every line a name and where the command was, and none lost'
        recorded.size() == 69
        recorded.every { it.size() == 2 && it[0] ==~ /[a-z0-9-]+|!/ && it[1] ==~ /shell|shell-interactive|profile:[a-z-]+(:synonym-of:[a-z-]+)?/ }
        (recorded as Set).size() == recorded.size()
        ofShell == ['create-app', 'create-plugin', 'create-web-plugin', 'create-profile', 'open', 'help', 'list-profiles', 'profile-info', 'gradle', 'run', '!', 'exit', 'quit'] as Set
        ofProfiles.containsAll(['run-app', 'run', 'stop', 'sh', 'war', 'test', 'create-controller', 'generate-all', 'create-feature', 'package-plugin'])
        ofProfiles.size() == 48

        and: 'none of them is typed without an answer: it is a command somewhere, or the table has a line for it; an exclamation mark is neither, as it runs a program on a line of the interactive console and nowhere else'
        (ofShell + ofProfiles - [ConsoleProgram.MARK]).findAll { String name ->
            FormerCommands.find(name) == null && !(['outside'] + PROJECTS.keySet()).any { String kind -> isCommand(kind, name) }
        } == TEST_TOOLING

        and: 'but for three that were there to test the REST API profiles themselves and not for an application: the table and the guide leave them out'
        TEST_TOOLING.every { String name -> name in ofProfiles }

        and: 'sh, which was another name of shell, is what is short for shell'
        FormerCommands.find('sh') == null
        isCommand('web', 'sh')
    }

    void "the guide lists the commands of earlier versions the table has, each with what became of it"() {
        given:
        File guide = new File(previousUsrDir, '../../grails-doc/src/en/guide/commandLine.adoc')
        List<String> section = guide.readLines('UTF-8').dropWhile { it != '=== Commands of Earlier Versions' }.drop(1).takeWhile { !it.startsWith('=== ') }
        Map<String, String> rows = [:]
        for (int i = 0; i < section.size(); i++) {
            def name = section[i] =~ /^\|`([^`]+)`$/
            if (name.matches()) {
                rows[name.group(1)] = section[i + 2]
            }
        }
        List<FormerCommands.Former> gone = FormerCommands.all().findAll { it.status != FormerCommands.Status.ELSEWHERE }

        expect:
        guide.isFile()
        rows.keySet() == (gone*.name + 'install') as Set
        gone.every { rows[it.name].startsWith("|${it.status.shown}".toString()) }
    }


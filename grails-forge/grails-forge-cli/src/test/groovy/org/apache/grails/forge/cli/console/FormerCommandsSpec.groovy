    private Set<String> commandsHere() {
        out.reset()
        assert ForgeCli.execute(beanContext, 'help', '--json') == 0
        Map described = (Map) new JsonSlurper().parseText(out.toString())
        out.reset()
        return ((List<Map>) described.commands).collectMany { [it.name] + (List) it.aliases } as Set<String>
    }

    private Set<String> commandsIn(List<String> create) {
        System.setProperty('user.dir', top.absolutePath)
        assert ForgeCli.execute(beanContext, create as String[]) == 0
        System.setProperty('user.dir', new File(top, create[1].substring('example.'.length())).absolutePath)
        Set<String> commands = commandsHere()
        System.setProperty('user.dir', top.absolutePath)
        err.reset()
        return commands
    }

    private void inProject(String kind) {
        commandsIn(PROJECTS[kind])
        System.setProperty('user.dir', new File(top, PROJECTS[kind][1].substring('example.'.length())).absolutePath)
    }

/**
 * What is said for a command the Grails shell or one of its profiles had and that is no command
 * where it is typed. The projects are generated by the create commands and are not built.
 */
class FormerCommandsSpec extends CommandSpec {

    static final String CLI = 'grails-forge-cli'
    static final String RECORD = '/former-commands-grails-8.tsv'
    static final Set<String> TEST_TOOLING = ['generate-unit-test', 'generate-functional-test', 'generate-resource-controller'] as Set
    static final String MISSING = 'The commands of the application and its plugins are not listed yet: a build that compiles the project lists them, ' +
            'and so does typing the name of one. To list them now: grails-forge-cli gradle grailsCommandCatalog'
    static final Map<String, List<String>> PROJECTS = [
            web        : ['create-app', 'example.web'],
            rest       : ['create-restapi', 'example.rest'],
            plugin     : ['create-plugin', 'example.plain'],
            'web-plugin': ['create-web-plugin', 'example.webplugin'],
            'rest-plugin': ['create-rest-api-plugin', 'example.restplugin'],
            quartz     : ['create-app', 'example.jobs', '--features', 'grails-quartz']]

    PrintStream originalOut
    PrintStream originalErr
    ByteArrayOutputStream out = new ByteArrayOutputStream()
    ByteArrayOutputStream err = new ByteArrayOutputStream()
    File top

    void setup() {
        originalOut = System.out
        originalErr = System.err
        System.setOut(new PrintStream(out, true))
        System.setErr(new PrintStream(err, true))
        top = dir
        // the projects are not built: a name of a command of a plugin does not have the build list the commands of the application
        ApplicationCommands.setListing('false')
    }

    void cleanup() {
        System.setOut(originalOut)
        System.setErr(originalErr)
        ConsoleProject.setOwnedByUser(null)
        ApplicationCommands.setListing(null)
    }

    @Unroll
    void "outside a project #typed is refused with what there is in its place"() {
        when:
        int exit = ForgeCli.execute(beanContext, typed)
        List<String> lines = err.toString().readLines()

        then: 'a mistake in the command line, as before, with one more line before how the command line is used'
        exit == 2
        out.toString().isEmpty()
        lines[0].startsWith("There is no command ${typed}")
        lines[1] == said
        lines[2] == 'Usage: grails-forge-cli [-hvVx] [--non-interactive] [--plain-output] [COMMAND]'

        and: 'and where the help is, which is not shown for a mistake'
        lines[3] == "Run 'grails-forge-cli help' for the commands"
        lines.size() == 4

        where:
        typed                      | said
        'test'                     | 'test was another name of test-app in the Grails shell. Type: grails-forge-cli test-app'
        'create-tag-lib'           | 'create-tag-lib is written in the web profile of the Grails shell as another name of create-taglib, in a place the shell did not read, so it was no command there either. Type: grails-forge-cli create-taglib'
        'run'                      | 'run was another name of run-app in a project in the Grails shell; outside a project it ran a Groovy script with Spring Boot, which has no replacement. Type: grails-forge-cli run-app'
        'stop'                     | 'stop was another name of stop-app in the Grails shell. Type: grails-forge-cli stop-app'
        'quit'                     | 'quit ended the interactive mode of the Grails shell. The interactive mode of grails-forge-cli is ended with exit, and there is none to end outside it'
        'list-profiles'            | 'list-profiles listed the profiles of the Grails shell. Profiles are replaced by application types and features: grails-forge-cli help lists the create commands, and each lists its features with --list-features'
        'open'                     | 'open opened a file with the program the desktop has for it in the Grails shell. It has no replacement in grails-forge-cli'
        'create-profile'           | 'create-profile created a profile for the Grails shell. Profiles are replaced by application types, features and feature packs, and no command creates any of these'
    }

    @Unroll
    void "outside a project #typed, which is a command of some projects, is known and says in one line that there is no project"() {
        when:
        int exit = ForgeCli.execute(beanContext, typed)

        then: 'no mistake in the command line: the same refusal as of every command of a project, and no line of the table'
        exit == 1
        out.toString().isEmpty()
        err.toString().readLines() == ["| Error ${typed} is a command of a Grails project; there is none in ${dir.canonicalPath} or above it".toString()]
        dir.list().length == 0

        where:
        typed << FormerCommands.all().findAll { it.status == FormerCommands.Status.ELSEWHERE }*.name
    }

    void "every command of the table is refused with its line where it is no command, and is a command where the table says it is one"() {
        given: 'the commands there are outside a project and in a project of every kind'
        Map<String, Set<String>> commands = [outside: commandsHere()]
        PROJECTS.each { String kind, List<String> create ->
            commands[kind] = commandsIn(create)
        }
        List<FormerCommands.Former> table = FormerCommands.all()
        Set<String> names = table*.name as Set

        expect: 'the table itself: one line each, of text only, that says the name and nothing a terminal or picocli acts on'
        table.size() == names.size()
        table*.name == table*.name.sort(false)
        table.every { FormerCommands.Former each ->
            each.hint.length() <= 400 && each.hint ==~ /[\x20-\x7e]+/ && !each.hint.contains('@|') && !each.hint.contains('%') &&
                    each.hint.startsWith(each.name + ' ') && !each.origin.isEmpty()
        }

        and: 'what the shell had and this command line does not have is a command nowhere'
        table.findAll { it.status != FormerCommands.Status.ELSEWHERE }.every { FormerCommands.Former each ->
            commands.values().every { !it.contains(each.name) }
        }

        and: 'a command of some directories only is one in a project of some kind'
        table.findAll { it.status == FormerCommands.Status.ELSEWHERE }.every { FormerCommands.Former each ->
            commands.findAll { it.key != 'outside' }.values().any { it.contains(each.name) }
        }

        and: 'every command that is not there in every kind of project is in the table, so that none is refused without a word'
        Map<String, Set<String>> inProjects = commands.findAll { it.key != 'outside' }
        (inProjects.values().flatten() as Set<String>).findAll { String name -> inProjects.values().any { !it.contains(name) } }.every { names.contains(it) }

        and: 'a command a line tells to type is a command of a web application'
        table.collect { (it.hint =~ /Type: \{cli\} ([a-z-]+)$/) }.findAll { it.find() }*.group(1).sort() == ['create-taglib', 'run-app', 'stop-app', 'test-app']
        ['create-taglib', 'run-app', 'stop-app', 'test-app', 'help', 'gradle', 'feature', 'create-app', 'create-unit-test'].every { commands.web.contains(it) }
        ['create-restful-controller', 'create-functional-test'].every { commands.rest.contains(it) }
        ['create-restful-controller', 'create-functional-test', 'package-plugin'].every { commands['rest-plugin'].contains(it) }

        and: 'in every directory, each of them is either a command or refused with its line and nothing else of the table'
        (['outside'] + PROJECTS.keySet()).every { String kind ->
            System.setProperty('user.dir', (kind == 'outside' ? top : new File(top, PROJECTS[kind][1].substring('example.'.length()))).absolutePath)
            table.every { FormerCommands.Former each ->
                out.reset()
                err.reset()
                int exit = ForgeCli.execute(beanContext, 'help', each.name)
                List<String> lines = err.toString().readLines()
                List<String> ofTheTable = lines.findAll { String line -> table.any { it.hint.replace('{cli}', CLI).replace('{name}', CLI) == line } }
                // outside a project a command of some projects is known too: it says there that it needs a project
                commands[kind].contains(each.name) || (kind == 'outside' && each.status == FormerCommands.Status.ELSEWHERE) ?
                        exit == 0 && lines.isEmpty() :
                        exit == 2 && lines[0].startsWith("There is no command ${each.name}") && ofTheTable == [each.hint.replace('{cli}', CLI).replace('{name}', CLI)] &&
                                lines.indexOf(ofTheTable[0]) == (kind == 'outside' ? 1 : 2)
            }
        }
    }

    void "in a project the line comes last, after the commands that are most like what was typed and after what is said about the commands of the application"() {
        given:
        inProject('web')

        when: 'a name the shell had that is close to a command there is'
        int exit = ForgeCli.execute(beanContext, 'create-tag-lib', 'Format')
        List<String> lines = err.toString().readLines()

        then:
        exit == 2
        lines[0].startsWith('There is no command create-tag-lib. Did you mean: ')
        lines[0].contains('create-taglib')
        lines[1] == MISSING
        lines[2] == 'create-tag-lib is written in the web profile of the Grails shell as another name of create-taglib, in a place the shell did not read, so it was no command there either. Type: grails-forge-cli create-taglib'
        lines[3] == 'Usage: grails-forge-cli [-hvVx] [--non-interactive] [--plain-output] [COMMAND]'
        lines[4] == "Run 'grails-forge-cli help' for the commands"
        lines.size() == 5
        !new File(top, 'web/grails-app/taglib/example/FormatTagLib.groovy').exists()

        when: 'a command of another kind of project'
        err.reset()
        exit = ForgeCli.execute(beanContext, 'create-restful-controller', 'Api')
        lines = err.toString().readLines()

        then:
        exit == 2
        lines[0].startsWith('There is no command create-restful-controller')
        lines[1] == MISSING
        lines[2] == 'create-restful-controller is a command in the directory of a REST API application or REST API plugin (create-restapi, create-rest-api-plugin), ' +
                'and the current directory is in none'

        when: 'a command of a plugin, which the build of the project may list'
        err.reset()
        exit = ForgeCli.execute(beanContext, 'generate-all', 'example.Book')
        lines = err.toString().readLines()

        then:
        exit == 2
        lines[1] == MISSING
        lines[2] == 'generate-all is a command of the scaffolding plugin (grails-scaffolding) for applications with GSP views: where the application has the plugin, ' +
                'it is a command here by its name. What the REST API profile generated with it (JSON views) has no replacement'

        when: 'a command the directory has'
        err.reset()
        exit = ForgeCli.execute(beanContext, 'create-taglib', '--help')

        then:
        exit == 0
        err.toString().isEmpty()
    }


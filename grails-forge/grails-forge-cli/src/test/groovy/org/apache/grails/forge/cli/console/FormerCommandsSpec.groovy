package org.apache.grails.forge.cli.console

import java.nio.file.Path
import java.util.function.Predicate
import groovy.json.JsonSlurper
import org.grails.forge.cli.CommandSpec
import org.grails.forge.cli.ForgeCli
import spock.lang.Unroll

/**
 * What is said for a command the Grails shell or one of its profiles had and that is no command
 * where it is typed. The projects are generated by the create commands and are not built.
 */
class FormerCommandsSpec extends CommandSpec {

    static final String CLI = 'grails-forge-cli'
    static final String MISSING = 'The commands of the application and its plugins are not listed: the project has no build/grails/command-catalog.json. ' +
            'They are listed after: grails-forge-cli gradle grailsCommandCatalog'
    static final Map<String, List<String>> PROJECTS = [
            web        : ['create-app', 'example.web'],
            rest       : ['create-restapi', 'example.rest'],
            plugin     : ['create-plugin', 'example.plain'],
            'web-plugin': ['create-web-plugin', 'example.webplugin'],
            quartz     : ['create-app', 'example.jobs', '--features', 'grails-quartz']]

    PrintStream originalOut
    PrintStream originalErr
    ByteArrayOutputStream out = new ByteArrayOutputStream()
    ByteArrayOutputStream err = new ByteArrayOutputStream()
    File top

    void setup() {
        originalOut = System.out
        originalErr = System.err
        System.setOut(new PrintStream(out, true))
        System.setErr(new PrintStream(err, true))
        top = dir
    }

    void cleanup() {
        System.setOut(originalOut)
        System.setErr(originalErr)
        ConsoleProject.setOwnedByUser(null)
    }

    @Unroll
    void "outside a project #typed is refused with what there is in its place"() {
        when:
        int exit = ForgeCli.execute(beanContext, typed)
        List<String> lines = err.toString().readLines()

        then: 'a mistake in the command line, as before, with one more line before how the command line is used'
        exit == 2
        out.toString().isEmpty()
        lines[0].startsWith("There is no command ${typed}")
        lines[1] == said
        lines[2] == 'Usage: grails-forge-cli [-hvVx] [--non-interactive] [--plain-output] [COMMAND]'

        where:
        typed                      | said
        'test'                     | 'test was another name of test-app in the Grails shell. Type: grails-forge-cli test-app'
        'create-tag-lib'           | 'create-tag-lib was another name of create-taglib in the Grails shell. Type: grails-forge-cli create-taglib'
        'quit'                     | 'quit ended the interactive mode of the Grails shell. The interactive mode of grails-forge-cli is ended with exit, and there is none to end outside it'
        'list-profiles'            | 'list-profiles listed the profiles of the Grails shell. Profiles are replaced by application types and features: grails-forge-cli help lists the create commands, and each lists its features with --list-features'
        'list-plugins'             | 'list-plugins listed the plugins of the Grails plugin portal in the Grails shell. It has no replacement in grails-forge-cli'
        'open'                     | 'open opened a file with the program the desktop has for it in the Grails shell. It has no replacement in grails-forge-cli'
        'create-profile'           | 'create-profile created a profile for the Grails shell. Profiles are replaced by application types, features and feature packs, and no command creates any of these'
        'generate-functional-test' | 'generate-functional-test was a command of the REST API profile of the Grails shell. It has no replacement in grails-forge-cli; create-functional-test writes an empty test in a REST API application'
        'create-controller'        | 'create-controller is a command in the directory of a Grails project whose record is read, and the current directory is in none'
        'create-restful-controller' | 'create-restful-controller is a command in the directory of a REST API application (create-restapi), and the current directory is in none'
        'publish-plugin'           | 'publish-plugin is a command in the directory of a Grails plugin, which has a class whose name ends with GrailsPlugin under src/main/groovy, and the current directory is in none'
    }

    void "every command of the table is refused with its line where it is no command, and is a command where the table says it is one"() {
        given: 'the commands there are outside a project and in a project of every kind'
        Map<String, Set<String>> commands = [outside: commandsHere()]
        PROJECTS.each { String kind, List<String> create ->
            commands[kind] = commandsIn(create)
        }
        List<FormerCommands.Former> table = FormerCommands.all()
        Set<String> names = table*.name as Set

        expect: 'the table itself: one line each, of text only, that says the name and nothing a terminal or picocli acts on'
        table.size() == names.size()
        table*.name == table*.name.sort(false)
        table.every { FormerCommands.Former each ->
            each.hint.length() <= 400 && each.hint ==~ /[\x20-\x7e]+/ && !each.hint.contains('@|') && !each.hint.contains('%') &&
                    (each.hint.startsWith(each.name + ' ') || each.name == '!') && !each.origin.isEmpty()
        }

        and: 'what the shell had and this command line does not have is a command nowhere'
        table.findAll { it.status != FormerCommands.Status.ELSEWHERE }.every { FormerCommands.Former each ->
            commands.values().every { !it.contains(each.name) }
        }

        and: 'a command of some directories only is one in a project of some kind, and is none outside a project'
        table.findAll { it.status == FormerCommands.Status.ELSEWHERE }.every { FormerCommands.Former each ->
            !commands.outside.contains(each.name) && commands.findAll { it.key != 'outside' }.values().any { it.contains(each.name) }
        }

        and: 'every command that is not there in every directory is in the table, so that none is refused without a word'
        (commands.values().flatten() as Set<String>).findAll { String name -> commands.values().any { !it.contains(name) } }.every { names.contains(it) }

        and: 'a command a line tells to type is a command of a web application'
        table.collect { (it.hint =~ /Type: \{cli\} ([a-z-]+)$/) }.findAll { it.find() }*.group(1).sort() == ['create-taglib', 'test-app']
        ['create-taglib', 'test-app', 'help', 'gradle', 'feature', 'create-app', 'create-unit-test'].every { commands.web.contains(it) }
        ['create-restful-controller', 'create-functional-test'].every { commands.rest.contains(it) }

        and: 'in every directory, each of them is either a command or refused with its line and nothing else of the table'
        (['outside'] + PROJECTS.keySet()).every { String kind ->
            System.setProperty('user.dir', (kind == 'outside' ? top : new File(top, PROJECTS[kind][1].substring('example.'.length()))).absolutePath)
            table.every { FormerCommands.Former each ->
                out.reset()
                err.reset()
                int exit = ForgeCli.execute(beanContext, 'help', each.name)
                List<String> lines = err.toString().readLines()
                List<String> ofTheTable = lines.findAll { String line -> table.any { it.hint.replace('{cli}', CLI) == line } }
                commands[kind].contains(each.name) ?
                        exit == 0 && lines.isEmpty() :
                        exit == 2 && lines[0].startsWith("There is no command ${each.name}") && ofTheTable == [each.hint.replace('{cli}', CLI)] &&
                                lines.indexOf(ofTheTable[0]) == (kind == 'outside' ? 1 : 2)
            }
        }
    }

    void "in a project the line comes last, after the commands that are most like what was typed and after what is said about the commands of the application"() {
        given:
        inProject('web')

        when: 'a name the shell had that is close to a command there is'
        int exit = ForgeCli.execute(beanContext, 'create-tag-lib', 'Format')
        List<String> lines = err.toString().readLines()

        then:
        exit == 2
        lines[0].startsWith('There is no command create-tag-lib. Did you mean: ')
        lines[0].contains('create-taglib')
        lines[1] == MISSING
        lines[2] == 'create-tag-lib was another name of create-taglib in the Grails shell. Type: grails-forge-cli create-taglib'
        lines[3] == 'Usage: grails-forge-cli [-hvVx] [--non-interactive] [--plain-output] [COMMAND]'
        !new File(top, 'web/grails-app/taglib/example/FormatTagLib.groovy').exists()

        when: 'a command of another kind of project'
        err.reset()
        exit = ForgeCli.execute(beanContext, 'create-functional-test', 'Api')
        lines = err.toString().readLines()

        then:
        exit == 2
        lines[0].startsWith('There is no command create-functional-test')
        lines[1] == MISSING
        lines[2] == 'create-functional-test is a command in the directory of a REST API application (create-restapi), and the current directory is in none'

        when: 'a command of a plugin, which the build of the project may list'
        err.reset()
        exit = ForgeCli.execute(beanContext, 'generate-all', 'example.Book')
        lines = err.toString().readLines()

        then:
        exit == 2
        lines[1] == MISSING
        lines[2] == 'generate-all is a command of the scaffolding plugin (grails-scaffolding) for applications with GSP views: where the application has the plugin, ' +
                'grails-forge-cli gradle grailsCommandCatalog makes it a command here. What the REST API profile generated with it (JSON views) has no replacement'

        when: 'a command the directory has'
        err.reset()
        exit = ForgeCli.execute(beanContext, 'create-taglib', '--help')

        then:
        exit == 0
        err.toString().isEmpty()
    }

    void "a command the build of the project lists is that command, whatever the table says about its name"() {
        given:
        inProject('web')
        File catalog = new File(top, 'web/build/grails/command-catalog.json')
        catalog.parentFile.mkdirs()
        catalog.text = '{"format":1,"complete":true,"diagnostics":[],"commands":[{"name":"generate-all","aliases":[],"description":"Generates all",' +
                '"origin":"org.apache.grails:grails-scaffolding-cli:9.0.0","target":"application","registration":"descriptor"}]}'

        when:
        int exit = ForgeCli.execute(beanContext, 'help', 'generate-all')

        then:
        exit == 0
        err.toString().isEmpty()
        out.toString().readLines()[0] == 'Usage: grails-forge-cli generate-all [ARGS...]'

        when: 'another one of the table, with a list of the commands of the application that is current'
        int other = ForgeCli.execute(beanContext, 'generate-views')

        then: 'nothing is said about the list, and the line of the table follows the refusal'
        other == 2
        err.toString().readLines()[1].startsWith('generate-views is a command of the scaffolding plugin')
    }

    void "below a project that is not used the reason comes first"() {
        given:
        assert ForgeCli.execute(beanContext, 'create-app', 'example.shop') == 0
        File project = new File(dir, 'shop')
        File below = new File(project, 'work')
        below.mkdirs()
        System.setProperty('user.dir', below.absolutePath)
        ConsoleProject.setOwnedByUser({ Path path -> path != project.canonicalFile.toPath() } as Predicate<Path>)
        out.reset()

        when:
        int exit = ForgeCli.execute(beanContext, 'create-controller', 'Book')
        List<String> lines = err.toString().readLines()

        then:
        exit == 2
        lines[0].startsWith('There is no command create-controller')
        lines[1].startsWith('The commands of a project are not there: The Grails project in ')
        lines[2] == 'create-controller is a command in the directory of a Grails project whose record is read, and the current directory is in none'
    }

    @Unroll
    void "what is not exactly a name of the table has no line: #shown"() {
        when:
        int exit = ForgeCli.execute(beanContext, typed)
        String said = err.toString()

        then:
        exit == 2
        said.readLines()[0].startsWith('There is no command ')
        !said.contains('Grails shell')
        !said.contains('\u001b')
        !said.contains('\u0007')
        said.readLines().findAll { it.startsWith('Usage: ') } == ['Usage: grails-forge-cli [-hvVx] [--non-interactive] [--plain-output] [COMMAND]']

        where:
        typed                          | shown
        'Test'                         | 'another case'
        'LIST-PLUGINS'                 | 'upper case'
        'test '                        | 'a space after it'
        ' list-plugins'                | 'a space before it'
        'list-plugins\n'               | 'a line break after it'
        'test\u001b[31m'               | 'an escape sequence after it'
        '\u001b]0;x\u0007list-plugins' | 'an escape sequence before it'
        'list-plugins\u0000'           | 'a NUL after it'
        'list‐plugins'            | 'another hyphen'
        'list-plugins@|red x|@'        | 'the markup of picocli'
        'list-plugins%n%s'             | 'a format'
        '${list-plugins}'              | 'a variable'
        'tes'                          | 'part of a name'
        ('list-plugins' * 400)         | 'a name many times'
    }

    @Unroll
    void "what follows an exclamation mark is not repeated: #shown"() {
        when:
        int exit = ForgeCli.execute(beanContext, typed)
        List<String> lines = err.toString().readLines()

        then:
        exit == 2
        lines[0].startsWith('There is no command ')
        lines[1] == 'An exclamation mark ran a program from the interactive mode of the Grails shell. It has no replacement in grails-forge-cli'
        lines[2] == 'Usage: grails-forge-cli [-hvVx] [--non-interactive] [--plain-output] [COMMAND]'
        !err.toString().contains('\u001b')
        lines.findAll { it.contains('/etc') }.size() <= 1

        where:
        typed                         | shown
        '!'                           | 'alone'
        '!ls'                         | 'a program'
        '!rm -rf /etc\u001b[2J@|red x|@' | 'a program with what a terminal acts on'
    }

    void "only a command at the top of the command line is looked up, and the help is the help"() {
        when: 'the name of a command of the shell where a command of feature is expected'
        int exit = ForgeCli.execute(beanContext, 'feature', 'test')

        then:
        exit == 2
        err.toString().readLines()[0].startsWith('There is no command test of feature')
        !err.toString().contains('Grails shell')

        when:
        err.reset()
        exit = ForgeCli.execute(beanContext, 'help', 'feature', 'list-plugins')

        then:
        exit == 2
        !err.toString().contains('Grails shell')

        when: 'the help was asked for before it'
        err.reset()
        exit = ForgeCli.execute(beanContext, '--help', 'list-plugins')

        then:
        exit == 0
        err.toString().isEmpty()
        out.toString().startsWith('Usage: grails-forge-cli [-hvVx] [--non-interactive] [--plain-output] [COMMAND]')

        when: 'a name of the table as the argument of a command'
        out.reset()
        exit = ForgeCli.execute(beanContext, 'create-app', 'list-plugins')

        then:
        exit == 0
        err.toString().isEmpty()
        new File(top, 'list-plugins/grails-app').isDirectory()
    }

    void "install, which the plugin profiles had, is still answered by the command line itself"() {
        expect:
        FormerCommands.find('install') == null

        when:
        int exit = ForgeCli.execute(beanContext, 'install')

        then:
        exit == 1
        (out.toString() + err.toString()).contains('Run: grails-forge-cli gradle publishToMavenLocal')
    }

    void "the guide lists the commands of earlier versions the table has, each with what became of it"() {
        given:
        File guide = new File(previousUsrDir, '../../grails-doc/src/en/guide/commandLine.adoc')
        List<String> section = guide.readLines('UTF-8').dropWhile { it != '=== Commands of Earlier Versions' }.drop(1).takeWhile { !it.startsWith('=== ') }
        Map<String, String> rows = [:]
        for (int i = 0; i < section.size(); i++) {
            def name = section[i] =~ /^\|`([^`]+)`$/
            if (name.matches()) {
                rows[name.group(1)] = section[i + 2]
            }
        }
        List<FormerCommands.Former> gone = FormerCommands.all().findAll { it.status != FormerCommands.Status.ELSEWHERE }

        expect:
        guide.isFile()
        rows.keySet() == (gone*.name + 'install') as Set
        gone.every { rows[it.name].startsWith("|${it.status.shown}".toString()) }
    }

    private Set<String> commandsHere() {
        out.reset()
        assert ForgeCli.execute(beanContext, 'help', '--json') == 0
        Map described = (Map) new JsonSlurper().parseText(out.toString())
        out.reset()
        return ((List<Map>) described.commands).collectMany { [it.name] + (List) it.aliases } as Set<String>
    }

    private Set<String> commandsIn(List<String> create) {
        System.setProperty('user.dir', top.absolutePath)
        assert ForgeCli.execute(beanContext, create as String[]) == 0
        System.setProperty('user.dir', new File(top, create[1].substring('example.'.length())).absolutePath)
        Set<String> commands = commandsHere()
        System.setProperty('user.dir', top.absolutePath)
        err.reset()
        return commands
    }

    private void inProject(String kind) {
        commandsIn(PROJECTS[kind])
        System.setProperty('user.dir', new File(top, PROJECTS[kind][1].substring('example.'.length())).absolutePath)
    }
}

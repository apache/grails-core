    void "a command that is added to the command line is found by its short form, and the name of a command is that command"() {
        given: 'commands as another part of the command line registers them'
        CommandLine commandLine = ForgeCli.createCommandLine(beanContext, true, false)
        ['check-all', 'clean-all', 'clean-up', 'cU'].each { String name -> commandLine.addSubcommand(name, new Sample()) }

        when: 'a short form only one of them has'
        int exit = ForgeCli.execute(commandLine, 'cheA', 'one', 'cA')

        then:
        exit == 0
        out.toString().readLines() == ['check-all ran with [one, cA]']

        when: 'what is the name of one command and short for another'
        out.reset()
        exit = ForgeCli.execute(commandLine, 'cU', 'two')

        then:
        exit == 0
        out.toString().readLines() == ['cU ran with [two]']

        when: 'a short form several commands have'
        out.reset()
        exit = ForgeCli.execute(commandLine, 'cA', 'three')

        then: 'none of them is run, and they are named'
        exit == 2
        out.toString().isEmpty()
        err.toString().readLines()[0] == 'cA is short for more than one command: create-app, check-all, clean-all. Type more of the name of the one that is meant'
        err.toString().contains('Usage: grails-forge-cli [-hvVx] [COMMAND]')
        !new File(dir, 'three').exists()

        when: 'help is asked for them'
        err.reset()
        int help = ForgeCli.execute(commandLine, 'help', 'cleA')
        int ambiguous = ForgeCli.execute(commandLine, 'help', 'cA')

        then:
        help == 0
        out.toString().startsWith('Usage: grails-forge-cli clean-all ')
        ambiguous == 2
        err.toString().readLines()[0].startsWith('cA is short for more than one command: create-app, check-all, clean-all.')

        when: 'the commands are described for a tool'
        out.reset()
        int json = ForgeCli.execute(commandLine, 'help', '--json')
        Map described = (Map) new JsonSlurper().parseText(out.toString())
        Map sample = ((List<Map>) described.commands).find { it.name == 'check-all' }

        then:
        json == 0
        sample.description == 'A command that says what it was given'
        sample.project
        sample.options.find { it.names == ['--loud'] }.arity == '0'
        sample.parameters == [[label: 'WORD', arity: '0..*', description: 'What to say']]
    }


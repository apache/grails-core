    void "the interactive shell completes the commands there are after the last command, not those it started with"() {
        given: 'a shell that was started outside a project'
        InteractiveShell shell = new InteractiveShell(ForgeCli.createCommandLine(beanContext, true), { String[] args -> }, null,
                { ForgeCli.createCommandLine(beanContext, true) } as Supplier<CommandLine>)

        expect:
        completedBy(shell).contains('create-app')
        completedBy(shell).contains('help')
        !completedBy(shell).contains('create-controller')

        when: 'the directory became a project, as by a command of the shell, and the command has ended'
        new File(dir, 'grails-forge-cli.yml').setText('applicationType: web\ndefaultPackage: com.example\nfeatures: [gorm-hibernate5]\n', 'UTF-8')
        shell.refresh()

        then:
        completedBy(shell).containsAll(['create-app', 'create-controller', 'add-property'])

        when: 'a shell that is not told how to look again'
        InteractiveShell fixed = new InteractiveShell(ForgeCli.createCommandLine(beanContext, true, false), { String[] args -> }, null)
        fixed.refresh()

        then: 'completes what it started with'
        !completedBy(fixed).contains('create-controller')
    }

    private static List<String> completedBy(InteractiveShell shell) {
        List<Candidate> candidates = []
        shell.completer().complete(null, new DefaultParser().parse('', 0), candidates)
        return candidates*.value()
    }

    private String shownBy(String... args) {
        out.reset()
        assert ForgeCli.execute(beanContext, args) == 0
        assert err.toString().isEmpty()
        return out.toString()
    }


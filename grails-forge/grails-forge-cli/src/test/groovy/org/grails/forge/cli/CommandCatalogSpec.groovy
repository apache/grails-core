    void "the commands are described as one JSON document, and nothing else is written"() {
        when:
        int exit = ForgeCli.execute(beanContext, 'help', '--json')
        Map described = (Map) new JsonSlurper().parseText(out.toString())
        List<Map> commands = (List<Map>) described.commands

        then:
        exit == 0
        err.toString().isEmpty()
        out.toString().readLines().size() == 1
        described.format == 1
        described.complete == true
        described.diagnostics == []
        described.projectDirectory == null

        and: 'every command the help lists, with what it needs'
        commands*.name.containsAll(['create-app', 'create-webapp', 'create-plugin', 'create-web-plugin', 'create-restapi', 'feature', 'gradle', 'help'])
        commands*.name.unique(false) == commands*.name
        commands.every { it.origin == 'built-in' && it.aliases == [] && it.description }
        commands.find { it.name == 'gradle' }.project == true
        commands.find { it.name == 'create-app' }.project == false
        commands.find { it.name == 'help' }.project == false
        commands.find { it.name == 'feature' }.commands*.name == ['add']
        commands.find { it.name == 'feature' }.commands[0].project == true
        commands.find { it.name == 'gradle' }.options == []
        commands.find { it.name == 'gradle' }.parameters == [[label: 'ARGS', arity: '1..*', description: 'The tasks to run and the options of Gradle, for example: build --offline']]
        commands.find { it.name == 'gradle' }.description == 'Runs Gradle in the Grails project of the current directory, with the Gradle wrapper of the project. ' +
                'Everything after gradle is given to Gradle as it is, the options too.'

        and: 'the options with their names and how many values they take'
        Map createApp = commands.find { it.name == 'create-app' }
        createApp.parameters*.label == ['NAME']
        createApp.options.find { it.names == ['-i', '--inplace'] }.arity == '0'
        createApp.options.find { it.names == ['-i', '--inplace'] }.label == null
        createApp.options.find { '--features' in it.names }.arity == '1'
        createApp.options.find { '--features' in it.names }.label == 'FEATURE'
        createApp.options.find { '--servlet' in it.names }.description.contains('Possible values: tomcat, jetty')
        !createApp.options.any { '--feature-pack-jar' in it.names }
        commands.find { it.name == 'help' }.options.find { it.names == ['--json'] }.required == false
    }

    void "in every directory of a project the commands are those of the project, and they write in the project"() {
        given: 'a generated application, and a directory inside it'
        assert ForgeCli.execute(beanContext, 'create-app', 'example.shop') == 0
        File project = new File(dir, 'shop').canonicalFile
        File inside = new File(project, 'grails-app/controllers/example')
        assert inside.isDirectory()
        System.setProperty('user.dir', inside.absolutePath)
        out.reset()

        when:
        int help = ForgeCli.execute(beanContext, 'help')

        then:
        help == 0
        out.toString().contains('create-controller')
        out.toString().contains('add-property')

        when: 'a class is created from there, by the short form of the command'
        out.reset()
        int controller = ForgeCli.execute(beanContext, 'cCont', 'Book')
        int domain = ForgeCli.execute(beanContext, 'create-domain-class', 'Book')
        int property = ForgeCli.execute(beanContext, 'aP', 'Book', 'title:String')

        then: 'it is where it belongs in the project, with the package of the project'
        controller == 0
        domain == 0
        property == 0
        new File(project, 'grails-app/controllers/example/BookController.groovy').text.contains('package example')
        new File(project, 'src/test/groovy/example/BookControllerSpec.groovy').isFile()
        new File(project, 'grails-app/domain/example/Book.groovy').text.contains('String title')
        inside.list().sort() == ['BookController.groovy', 'UrlMappings.groovy']
        err.toString().isEmpty()

        when: 'a class of a command that came later, the templates, and a class from a template of the project, from there'
        out.reset()
        int unitTest = ForgeCli.execute(beanContext, 'create-unit-test', 'Checkout')
        int installed = ForgeCli.execute(beanContext, 'install-templates')
        new File(project, 'src/main/templates/artifacts/Service.groovy').setText('// ours\n@artifact.package@\n\nclass @artifact.name@Service { }\n', 'UTF-8')
        int service = ForgeCli.execute(beanContext, 'cSe', 'Checkout')

        then: 'the templates are those of the project, read and written at its top'
        unitTest == 0
        installed == 0
        service == 0
        new File(project, 'src/test/groovy/example/CheckoutSpec.groovy').isFile()
        new File(project, 'src/main/templates/artifacts/Controller.groovy').isFile()
        new File(project, 'src/main/templates/testing/Generic.groovy').isFile()
        new File(project, 'grails-app/services/example/CheckoutService.groovy').text.startsWith('// ours\npackage example')
        out.toString().contains('| Using the template src/main/templates/artifacts/Service.groovy of the project')
        inside.list().sort() == ['BookController.groovy', 'UrlMappings.groovy']
        err.toString().isEmpty()

        when: 'a short form that two commands of the project have'
        int ambiguous = ForgeCli.execute(beanContext, 'cC', 'Other')

        then: 'neither is run'
        ambiguous == 2
        err.toString().readLines()[0] == 'cC is short for more than one command: create-controller, create-command. Type more of the name of the one that is meant'
        !new File(project, 'grails-app/controllers/example/OtherController.groovy').exists()
        !new File(project, 'grails-app/commands/example/OtherCommand.groovy').exists()

        when: 'a feature is added from there'
        out.reset()
        int feature = ForgeCli.execute(beanContext, 'feature', 'add', 'grails-quartz', '--dry-run')

        then:
        feature == 0
        out.toString().contains('To add the feature grails-quartz')
        out.toString().contains('build.gradle')

        when: 'the commands are described there'
        out.reset()
        int json = ForgeCli.execute(beanContext, 'help', '--json')
        Map described = (Map) new JsonSlurper().parseText(out.toString())

        then:
        json == 0
        described.projectDirectory == project.path
        described.complete == true
        ((List<Map>) described.commands).findAll { it.project }*.name.containsAll(['gradle', 'create-controller', 'create-service', 'create-domain-class', 'add-property'])
    }


    // the build file of the application created with cache by this version, in the directory other
    private List<String> cacheBuildFile() {
        create(other, 'create-app', 'com.example.shop', '--features', 'cache')
        List<String> withCache = lines(new File(other, 'shop/build.gradle').text)
        assert withCache.count(CACHE) == 1
        return withCache
    }

    /**
     * Makes a file of the baseline what an earlier template wrote, with the digest of the index; the
     * lock is bound to the index again by {@link #writtenBy}.
     */
    private void earlierBaseline(String path, String content) {
        File copy = new File(project, ".grails/baseline/files/${path}")
        File index = new File(project, '.grails/baseline/index.yml')
        String generated = sha(copy.bytes)
        assert index.text.count(generated) == 1
        copy.setText(content, 'UTF-8')
        index.text = index.text.replace(generated, sha(content.getBytes('UTF-8')))
    }

    /**
     * Makes the record one that another version or build wrote: the version of Grails in the manifest
     * and the lock, the version and the identity of the generator in the lock, with the digests that
     * bind them.
     */
    private void writtenBy(String version, String generatorSha256, boolean reads = true) {
        File manifest = new File(project, '.grails/project.yml')
        File lock = new File(project, '.grails/forge.lock.yml')
        File index = new File(project, '.grails/baseline/index.yml')
        boolean grails = version != VersionInfo.version
        if (grails) {
            manifest.text = manifest.text.replace("grailsVersion: ${VersionInfo.grailsVersion}\n", "grailsVersion: ${version}\n")
        }
        String body = lock.text.replace("  version: ${VersionInfo.version}\n  sha256: ${VersionInfo.generatorSha256}\n", "  version: ${version}\n  sha256: ${generatorSha256}\n")
        if (grails) {
            body = body.replace("\ngrailsVersion: ${VersionInfo.grailsVersion}\n", "\ngrailsVersion: ${version}\n")
        }
        body = body.replaceFirst('manifest:\n  sha256: [0-9a-f]{64}', "manifest:\n  sha256: ${sha(manifest.bytes)}")
                .replaceFirst('baselineIndex:\n  sha256: [0-9a-f]{64}', "baselineIndex:\n  sha256: ${sha(index.bytes)}")
        body = body.substring(0, body.lastIndexOf('seal:\n'))
        lock.text = body + "seal:\n  sha256: ${sha(body.bytes)}\n"
        assert !reads || ProjectState.read(project.toPath()).lock.generatorSha256 == generatorSha256
    }

    private static List<String> lines(String text) {
        return text.split('\n', -1).toList()
    }

    private static String text(List<String> lines) {
        return lines.join('\n')
    }

    // a command in the directory it is given
    private int create(File directory, String... arguments) {
        String current = System.getProperty('user.dir')
        System.setProperty('user.dir', directory.absolutePath)
        try {
            return ForgeCli.execute(beanContext, arguments)
        } finally {
            System.setProperty('user.dir', current)
            out.reset()
        }
    }

    // a command in the application
    private int run(String... arguments) {
        String current = System.getProperty('user.dir')
        System.setProperty('user.dir', project.absolutePath)
        try {
            return ForgeCli.execute(beanContext, arguments)
        } finally {
            System.setProperty('user.dir', current)
        }
    }

    // every file of the application outside .grails, with the digest of its content
    private static Map<String, String> applicationFiles(File project) {
        return tree(project).findAll { String path, String digest -> !path.startsWith('.grails/') && path != '.grails' }
    }

    // every file and directory of a project, but the lock of the changes, with the digest of each file
    private static Map<String, String> tree(File project) {
        Map<String, String> entries = new TreeMap<>()
        Files.walk(project.toPath()).withCloseable { stream ->
            stream.each { Path path ->
                String name = project.toPath().relativize(path).join('/')
                if (name.isEmpty() || name == '.grails/transactions' || name == '.grails/transactions/lock') {
                    return
                }
                entries.put(name, Files.isDirectory(path, LinkOption.NOFOLLOW_LINKS) ? 'directory' : sha(Files.readAllBytes(path)))
            }
        }
        return entries
    }

    // every file under a directory of a project, with the digest of its content
    private static Map<String, String> files(File project, String under) {
        Map<String, String> files = new TreeMap<>()
        Path root = project.toPath()
        Files.walk(root.resolve(under)).withCloseable { stream ->
            stream.filter { Files.isRegularFile(it) }.each { Path path -> files.put(root.relativize(path).join('/'), sha(Files.readAllBytes(path))) }
        }
        return files
    }

    private static String sha(byte[] bytes) {
        return MessageDigest.getInstance('SHA-256').digest(bytes).encodeHex().toString()
    }

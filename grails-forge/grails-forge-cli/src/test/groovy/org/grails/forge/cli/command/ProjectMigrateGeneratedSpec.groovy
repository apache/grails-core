                "${VersionInfo.grailsVersion}, which is earlier: a record is moved to a later version, and not to an earlier one. Use the command line of Grails " +
                '99.0.0, which wrote the record. Nothing was changed')
        out.toString().isEmpty()
        tree(project) == before

        when: 'feature add, project show and feature list'
        err.reset()
        int added = run('feature', 'add', 'cache')
        String refusal = err.toString()
        out.reset()
        run('project', 'show')
        String shown = out.toString()
        out.reset()

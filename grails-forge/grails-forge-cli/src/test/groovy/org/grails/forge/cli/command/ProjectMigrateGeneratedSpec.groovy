/**
 * {@code project migrate} on an application that Grails 9 generated, whose record an earlier version
 * of the command line wrote, or another build of this version: the record is moved to this version,
 * from the choices it has, and no other file of the application is written. The record is made one
 * that an earlier version wrote as the lock and the manifest of such a version are, with the digests
 * that bind them, and with a file of the baseline as an earlier template wrote it.
 */
class ProjectMigrateGeneratedSpec extends CommandSpec {

    private static final List<String> RECORD = ['.grails/project.yml', '.grails/forge.lock.yml', '.grails/baseline/index.yml']

    private static final String EARLIER = '9.0.0-M1'

    // what the template of the earlier version had at the top of the build file
    private static final String EARLIER_LINE = '// Generated by Grails 9.0.0-M1'

    private static final String CACHE = '    implementation "org.apache.grails:grails-cache"'

    PrintStream originalOut
    PrintStream originalErr
    ByteArrayOutputStream out = new ByteArrayOutputStream()
    ByteArrayOutputStream err = new ByteArrayOutputStream()

    File home
    String previousHome
    File other

    /** The application, created in the directory of the spec */
    File project

    void setup() {
        originalOut = System.out
        originalErr = System.err
        System.setOut(new PrintStream(out))
        System.setErr(new PrintStream(err))
        // where a change of a project that was interrupted is looked for
        home = Files.createTempDirectory('grailsforgehome').toFile()
        previousHome = System.getProperty('user.home')
        System.setProperty('user.home', home.absolutePath)
        other = Files.createTempDirectory('grailsforgeother').toFile()
        project = new File(dir, 'shop')
    }

    void cleanup() {
        System.setOut(originalOut)
        System.setErr(originalErr)
        System.setProperty('user.home', previousHome)
        home.deleteDir()
        other.deleteDir()
    }

    void "the record an earlier version wrote is moved to this version, the application is not touched, and a feature is added afterwards with every line of the application kept"() {
        given: 'an application whose build file an earlier template wrote with a line of its own, and which has a change of yours'
        create(dir, 'create-app', 'com.example.shop')
        List<String> generated = lines(new File(project, 'build.gradle').text)
        List<String> withCache = cacheBuildFile()
        List<String> earlier = [EARLIER_LINE] + generated
        earlierBaseline('build.gradle', text(earlier))
        new File(project, 'build.gradle').text = text(earlier + ['// mine'])
        writtenBy(EARLIER, 'ab' * 32)
        Map<String, String> application = applicationFiles(project)

        when: 'feature add is run with this version'
        int refused = run('feature', 'add', 'cache')

        then: 'it is refused, and names the command that moves the record'
        refused == 1
        err.toString().contains("The application was generated by grails-forge ${EARLIER} for Grails ${EARLIER}, and this is grails-forge ${VersionInfo.version} " +
                "for Grails ${VersionInfo.grailsVersion}: the application is generated again, to add a feature to it or to compare it, by the generator whose record " +
                'it has, and its record is moved to this version first. Nothing was changed. grails-forge-cli project migrate moves the record to this version, from ' +
                'the choices it has, and changes no file of the application outside .grails')

        when: 'the record is moved'
        err.reset()
        int moved = run('project', 'migrate')
        List<String> said = out.toString().readLines()

        then: 'what changes in the record is said, and nothing but the record is written'
        moved == 0
        err.toString().isEmpty()
        said[0] == '| The record of how the application shop was generated, moved to this version: the application is generated again from the choices the ' +
                'record has, and nothing but the record is written'
        said[1] == "    generator  grails-forge ${EARLIER} for Grails ${EARLIER} (generator sha256 ${'ab' * 6}), now grails-forge ${VersionInfo.version} for Grails " +
                "${VersionInfo.grailsVersion} (generator sha256 ${VersionInfo.generatorSha256.take(12)})"
        said[2] == '    changed  build.gradle'
        said[3] == '| 1 file of the baseline, in .grails/baseline/files, is not as this version generates it: 1 changed. The record names this version'
        said.contains('| The record was moved to this version: .grails/project.yml, .grails/forge.lock.yml and the baseline under .grails/baseline were written. ' +
                'No other file of the project was changed. Commit the directory .grails')
        said.contains('| Where a file of the application is not what this version generates, as where an earlier version generated it otherwise, ' +
                'grails-forge-cli feature add takes it for your change and keeps it; grails-forge-cli project regenerate --diff names those files')
        applicationFiles(project) == application

        and: 'the record is the one create-app writes for the same choices now'
        File fresh = new File(other, 'fresh')
        fresh.mkdirs()
        create(fresh, 'create-app', 'com.example.shop') == 0
        RECORD.every { new File(project, it).bytes == new File(fresh, "shop/${it}").bytes }
        files(project, '.grails/baseline') == files(new File(fresh, 'shop'), '.grails/baseline')
        ProjectState.read(project.toPath()).lock.generatorSha256 == VersionInfo.generatorSha256

        when: 'the files that are not as this version generates them are named'
        out.reset()
        int compared = run('project', 'regenerate', '--diff')

        then: 'the build file is one, with the line of the earlier template and yours'
        compared == 1
        out.toString().readLines() == ['changed  build.gradle', '| 1 file is not as the application was generated: 1 changed']

        when: 'the record is moved again'
        out.reset()
        int again = run('project', 'migrate')

        then: 'there is nothing to move'
        again == 0
        out.toString().readLines() == ["| The record of the application shop was written by this build of the command line, grails-forge ${VersionInfo.version} for Grails " +
                                               "${VersionInfo.grailsVersion}: it is that of this version already, and there is nothing to move. Nothing was written".toString()]

        when: 'a feature is added'
        out.reset()
        int added = run('feature', 'add', 'cache')

        then: 'the line of the earlier template and yours are kept as changes of yours, and the feature is merged among them'
        added == 0
        out.toString().contains('    merge    build.gradle (your changes are kept)')
        new File(project, 'build.gradle').text == text([EARLIER_LINE] + withCache + ['// mine'])

        and: 'the record is that of an application created with the feature by this version'
        RECORD.every { new File(project, it).bytes == new File(other, "shop/${it}").bytes }
        files(project, '.grails/baseline') == files(new File(other, 'shop'), '.grails/baseline')
    }

    void "a change of yours next to the lines the feature adds is a conflict after the record was moved, and nothing is written over"() {
        given: 'a line next to where the feature adds its dependency, which you changed'
        create(dir, 'create-app', 'com.example.shop')
        List<String> generated = lines(new File(project, 'build.gradle').text)
        List<String> withCache = cacheBuildFile()
        int at = withCache.indexOf(CACHE)
        assert at > 0 && generated[at] == withCache[at + 1]
        List<String> earlier = [EARLIER_LINE] + generated
        earlierBaseline('build.gradle', text(earlier))
        List<String> yours = new ArrayList<>(earlier)
        yours[at + 1] = yours[at + 1] + ' // mine'
        File build = new File(project, 'build.gradle')
        build.text = text(yours)
        writtenBy(EARLIER, 'ab' * 32)
        assert run('project', 'migrate') == 0
        String before = build.text
        out.reset()

        when:
        int added = run('feature', 'add', 'cache')

        then: 'the place is a conflict, and the file stays as it is'
        added == 1
        out.toString().contains('    conflict build.gradle: the feature changes lines of this file that were changed in the project too, or lines next to them')
        err.toString().contains('The feature was not added: 1 file cannot be written without losing what the application has. Nothing was changed.')
        build.text == before
    }


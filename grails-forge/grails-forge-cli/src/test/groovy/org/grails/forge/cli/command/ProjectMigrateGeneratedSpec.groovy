    void "a move that was interrupted is undone by the next command, which then moves the record"() {
        given:
        create(dir, 'create-app', 'com.example.shop')
        earlierBaseline('build.gradle', text([EARLIER_LINE] + lines(new File(project, 'build.gradle').text)))
        writtenBy(EARLIER, 'ab' * 32)
        Map<String, String> before = tree(project)
        FeatureAddition addition = new FeatureAddition(beanContext.getBean(ProjectGenerator))
        try {
            addition.migrate(project.toPath(), new ProjectShowCommand().getOperatingSystem(), []).apply { String path ->
                if (path == '.grails/baseline/index.yml') {
                    throw new IllegalStateException('the program ended')
                }
            }
        } catch (IllegalStateException ignored) {
        }

        expect: 'the record is half moved'
        tree(project) != before
        new File(home, '.grails/forge/transactions').list().size() == 1

        when: 'nothing is looked at while it is'
        int preview = run('project', 'migrate', '--dry-run')

        then:
        preview == 1
        err.toString().contains('An earlier change of the project was interrupted; it is undone when the record is moved, or a feature is added, without --dry-run')

        when:
        out.reset()
        int moved = run('project', 'migrate')
        String said = out.toString()
        File fresh = new File(other, 'fresh')
        fresh.mkdirs()
        create(fresh, 'create-app', 'com.example.shop')

        then: 'the change is undone, and the record is moved'
        moved == 0
        said.contains('An earlier change of the application that was interrupted was undone. 2 files were put back as they were: ' +
                '.grails/baseline/files/build.gradle, .grails/baseline/index.yml')
        said.contains('The record was moved to this version')
        RECORD.every { new File(project, it).bytes == new File(fresh, "shop/${it}").bytes }
        !new File(home, '.grails/forge/transactions').list()
    }


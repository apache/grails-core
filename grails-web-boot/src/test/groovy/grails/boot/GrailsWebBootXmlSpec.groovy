package grails.boot

import org.springframework.util.ClassUtils

import spock.lang.Specification

/**
 * Applications generated by forge or a profile list grails-web-boot, and the other Grails modules, rather than the web
 * starter, so grails-web-boot brings the grails-xml module that the starter brings, through Grails 9.
 */
class GrailsWebBootXmlSpec extends Specification {

    void 'an application that lists grails-web-boot rather than the web starter keeps XML'() {
        expect:
        ClassUtils.isPresent('grails.converters.XML', getClass().classLoader)
        ClassUtils.isPresent('org.grails.plugins.xml.XmlGrailsPlugin', getClass().classLoader)
    }
}

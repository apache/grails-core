package org.grails.compiler.injection

import java.nio.file.Files

import groovy.transform.CompileStatic
import groovy.transform.PackageScope

import org.apache.grails.plugin.descriptor.PluginDescriptorWriter

/** Reconciles only compiler-owned descriptors against the surviving classes in a class directory. */
@CompileStatic
@PackageScope
final class CompilerPluginDescriptors {

    private static final String GENERATED = '# Generated by the Grails compiler.'

    private CompilerPluginDescriptors() {
    }

    static void reconcile(File directory, String defaultVersion, boolean publishXml) {
        File imports = new File(directory, PluginDescriptorWriter.PLUGINS_IMPORTS_PATH)
        List<String> previous = imports.isFile() ? imports.readLines('UTF-8') : []
        if (imports.exists() && (!previous || previous.first() != GENERATED)) {
            return
        }
        def scan = PluginDescriptorWriter.scan(Collections.singleton(directory))
        Set<String> names = scan.plugins.collect { it.logicalName }.toSet()
        if (names) {
            PluginDescriptorWriter.writeDescriptors(scan.plugins, scan.artefactsByType, defaultVersion, null, directory, publishXml)
            imports.setText(([GENERATED] + names).join('\n') + '\n', 'UTF-8')
        }
        for (String line : previous) {
            if (line ==~ /[A-Za-z0-9][A-Za-z0-9._-]*/ && !line.contains('..') && !names.contains(line)) {
                File descriptor = new File(directory, PluginDescriptorWriter.PLUGIN_DESCRIPTORS_PREFIX +
                        line + '/' + PluginDescriptorWriter.PLUGIN_PROPERTIES_FILE)
                Files.deleteIfExists(descriptor.toPath())
            }
        }
        if (previous && !names) {
            Files.deleteIfExists(imports.toPath())
            if (publishXml) {
                Files.deleteIfExists(new File(directory, 'META-INF/grails-plugin.xml').toPath())
            }
        }
    }
}

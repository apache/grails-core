package org.grails.compiler.injection

import java.nio.file.Files

import groovy.transform.CompilationUnitAware
import groovy.transform.CompileStatic
import org.codehaus.groovy.ast.ASTNode
import org.codehaus.groovy.ast.ClassHelper
import org.codehaus.groovy.control.CompilationUnit
import org.codehaus.groovy.control.Phases
import org.codehaus.groovy.control.SourceUnit
import org.codehaus.groovy.transform.ASTTransformation
import org.codehaus.groovy.transform.GroovyASTTransformation

import grails.plugins.metadata.GrailsPluginDescriptor
import org.apache.grails.plugin.descriptor.PluginDescriptorWriter

/**
 * Publishes descriptors beside the classes produced by a standalone Groovy compilation.
 * Builds with a dedicated packaging task disable this transform on that source set.
 */
@CompileStatic
@GroovyASTTransformation
class PluginDescriptorTransformation implements ASTTransformation, CompilationUnitAware {

    private static final String GENERATED = '# Generated by the Grails compiler.'
    private static final String DECLARATION = '# plugin-class '

    CompilationUnit compilationUnit
    private final Map<File, Set<String>> declarations = [:]

    @Override
    void visit(ASTNode[] nodes, SourceUnit source) {
        File target = source.configuration.targetDirectory
        if (source.class.name == 'org.codehaus.jdt.groovy.control.EclipseSourceUnit') {
            target = GroovyEclipseCompilationHelper.resolveEclipseCompilationTargetDirectory(source)
        }
        if (target == null) {
            return
        }
        File imports = new File(target, PluginDescriptorWriter.PLUGINS_IMPORTS_PATH)
        def classes = source.AST.classes
        String fileName = new File(source.name).name
        boolean declaresPlugin = classes.any { type ->
            fileName == type.nameWithoutPackage + '.groovy' &&
                    (fileName.endsWith('GrailsPlugin.groovy') ||
                            !type.getAnnotations(ClassHelper.make(GrailsPluginDescriptor)).empty)
        }
        if (!declaresPlugin && !imports.isFile()) {
            return
        }
        if (!declarations.containsKey(target)) {
            declarations[target] = new LinkedHashSet<>()
            compilationUnit.addPhaseOperation({ SourceUnit unit ->
                if (unit.is(source)) {
                    reconcile(imports, declarations[target], target)
                }
            } as CompilationUnit.ISourceUnitOperation, Phases.OUTPUT)
        }
        if (declaresPlugin) {
            classes.each { declarations[target].add(it.name) }
        }
    }

    private static void reconcile(File imports, Set<String> candidates, File target) {
        List<String> previous = imports.isFile() ? imports.readLines('UTF-8') : []
        // A hand-authored index in a shared resources/classes directory takes precedence.
        if (previous && previous.first() != GENERATED) {
            return
        }
        Set<String> names = new LinkedHashSet<>(candidates)
        previous.findAll { it.startsWith(DECLARATION) }.each { names.add(it.substring(DECLARATION.length())) }
        def scan = PluginDescriptorWriter.scan(Collections.singleton(target))
        def plugins = scan.plugins.findAll { names.contains(it.className) }
        Set<String> current = plugins.collect { it.logicalName }.toSet()
        for (String line : previous) {
            if (line ==~ /[A-Za-z0-9][A-Za-z0-9._-]*/ && !line.contains('..') && !current.contains(line)) {
                File stale = new File(target, PluginDescriptorWriter.PLUGIN_DESCRIPTORS_PREFIX +
                        line + '/' + PluginDescriptorWriter.PLUGIN_PROPERTIES_FILE)
                Files.deleteIfExists(stale.toPath())
            }
        }
        if (!plugins) {
            Files.deleteIfExists(imports.toPath())
            return
        }
        PluginDescriptorWriter.writeDescriptors(plugins, scan.artefactsByType, null, null, target, false)
        List<String> lines = [GENERATED]
        lines.addAll(plugins.collect { DECLARATION + it.className })
        lines.addAll(current)
        imports.setText(lines.join('\n') + '\n', 'UTF-8')
    }
}

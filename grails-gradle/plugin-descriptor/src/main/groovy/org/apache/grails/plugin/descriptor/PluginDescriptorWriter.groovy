package org.apache.grails.plugin.descriptor

import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.nio.file.StandardCopyOption

import groovy.io.FileType
import groovy.transform.CompileStatic
import org.objectweb.asm.AnnotationVisitor
import org.objectweb.asm.ClassReader
import org.objectweb.asm.ClassVisitor
import org.objectweb.asm.Opcodes
import org.objectweb.asm.Type

import grails.plugins.metadata.PluginDefinition

/**
 * Reads the plugins declared in compiled classes and writes their descriptors.
 *
 * <p>A plugin is a concrete class annotated with {@code @GrailsPluginDescriptor}. Its descriptor, written
 * to {@code META-INF/grails/plugins/<name>/plugin.properties}, is the annotation together with the
 * plugin's version, the {@code @Artefact} classes compiled beside it and the auto-configuration its
 * {@code beans} block compiled onto, when it has one; the names are listed in
 * {@code META-INF/grails/plugins.imports}.</p>
 *
 * @since 9.0
 */
@CompileStatic
final class PluginDescriptorWriter {

    static final String PLUGINS_IMPORTS_PATH = 'META-INF/grails/plugins.imports'
    static final String PLUGIN_DESCRIPTORS_PREFIX = 'META-INF/grails/plugins/'
    static final String PLUGIN_PROPERTIES_FILE = 'plugin.properties'
    static final String GENERATED_HEADER = '# Generated by the Grails compiler. Do not edit.'

    private static final String CLASS_FILE_EXTENSION = '.class'
    private static final String PLUGIN_DESCRIPTOR_ANNOTATION = 'Lgrails/plugins/metadata/GrailsPluginDescriptor;'
    private static final String ARTEFACT_ANNOTATION = 'Lgrails/artefact/Artefact;'
    // CLASS retention: in the class file, though not at runtime. On a plugin the compiler sets its
    // autoConfigurationName to the qualified name of the auto-configuration the beans block compiled onto.
    private static final String GRAILS_BEANS_ANNOTATION = 'Lgrails/compiler/beans/GrailsBeans;'
    private static final String AUTO_CONFIGURATION_NAME = 'autoConfigurationName'

    private PluginDescriptorWriter() {
    }

    /** A class annotated with {@code @GrailsPluginDescriptor}, with the attributes it sets. */
    static final class DeclaredPlugin {
        final String className
        final Map<String, Object> attributes

        DeclaredPlugin(String className, Map<String, Object> attributes) {
            this.className = className
            this.attributes = Collections.unmodifiableMap(attributes)
        }
    }

    /** The plugins and artefacts found in a set of class directories. */
    static final class ScanResult {
        final List<DeclaredPlugin> plugins
        final Map<String, SortedSet<String>> artefactsByType

        ScanResult(List<DeclaredPlugin> plugins, Map<String, SortedSet<String>> artefactsByType) {
            this.plugins = plugins
            this.artefactsByType = artefactsByType
        }

        /**
         * The definitions of the plugins found. Every plugin of a directory is given the artefacts
         * compiled there, except those its {@code pluginExcludes} match.
         *
         * @param pluginVersion the version of the build, or {@code null}
         * @param defaultGrailsVersion the range for a plugin that declares none, or {@code null}
         */
        List<PluginDefinition> definitions(String pluginVersion, String defaultGrailsVersion) {
            List<PluginDefinition> definitions = plugins.collect { DeclaredPlugin plugin ->
                List<String> excludes = (List<String>) plugin.attributes.get('pluginExcludes') ?: List.<String>of()
                Map<String, List<String>> artefacts = new TreeMap<>()
                artefactsByType.each { String type, SortedSet<String> names ->
                    List<String> included = names.findAll { String name -> !isExcluded(name, excludes) }.toList()
                    if (included) {
                        artefacts.put(type, included)
                    }
                }
                PluginDefinition.fromDeclaration(plugin.className, plugin.attributes, pluginVersion, defaultGrailsVersion, artefacts)
            }
            Map<String, PluginDefinition> byName = new TreeMap<>()
            for (PluginDefinition definition : definitions) {
                PluginDefinition previous = byName.putIfAbsent(definition.pluginName, definition)
                if (previous != null) {
                    throw new IllegalArgumentException("Duplicate Grails plugin name '${definition.pluginName}' declared by " +
                            "${previous.pluginClass} and ${definition.pluginClass}")
                }
            }
            List.copyOf(byName.values())
        }
    }

    /** Scans class directories for plugin declarations and {@code @Artefact} classes. */
    static ScanResult scan(Set<File> classesDirs) {
        List<DeclaredPlugin> plugins = []
        Map<String, SortedSet<String>> artefactsByType = new TreeMap<>()
        Set<String> classNames = new HashSet<>()
        classesDirs.each { File dir ->
            if (!dir.exists()) {
                return
            }
            dir.eachFileRecurse(FileType.FILES) { File file ->
                if (!file.name.endsWith(CLASS_FILE_EXTENSION)) {
                    return
                }
                // A nested class can declare a plugin; closures and other inner classes are never artefacts
                boolean nested = file.name.contains('$')
                ClassReader reader
                try {
                    reader = new ClassReader(file.bytes)
                }
                catch (IOException | IllegalArgumentException e) {
                    throw new IllegalArgumentException("Could not read ${file} while generating plugin descriptors", e)
                }
                ClassScanner scanner = new ClassScanner()
                reader.accept(scanner, ClassReader.SKIP_CODE | ClassReader.SKIP_DEBUG | ClassReader.SKIP_FRAMES)
                String className = reader.className.replace('/' as char, '.' as char)
                classNames.add(className)
                if (!scanner.concrete) {
                    return
                }
                if (scanner.declaration != null) {
                    if (scanner.autoConfiguration) {
                        scanner.declaration.put(PluginDefinition.AUTO_CONFIGURATION_ATTRIBUTE, scanner.autoConfiguration)
                    }
                    plugins.add(new DeclaredPlugin(className, scanner.declaration))
                }
                else if (!nested && scanner.providedArtefact) {
                    artefactsByType.computeIfAbsent(scanner.artefactType) { new TreeSet<String>() }.add(className)
                }
            }
        }
        // an autoConfigurationName names the generated auto-configuration only once the compiler generated it
        List<DeclaredPlugin> declared = plugins.collect { DeclaredPlugin plugin ->
            String autoConfiguration = (String) plugin.attributes.get(PluginDefinition.AUTO_CONFIGURATION_ATTRIBUTE)
            if (!autoConfiguration || classNames.contains(autoConfiguration)) {
                return plugin
            }
            Map<String, Object> attributes = new LinkedHashMap<>(plugin.attributes)
            attributes.remove(PluginDefinition.AUTO_CONFIGURATION_ATTRIBUTE)
            new DeclaredPlugin(plugin.className, attributes)
        }
        declared.sort { DeclaredPlugin plugin -> plugin.className }
        new ScanResult(declared, artefactsByType)
    }

    /**
     * Writes the descriptors of the given plugins into a class directory and returns their names.
     *
     * @param configFiles the plugin configuration files ({@code plugin.yml}, {@code plugin.groovy}) to copy
     *        beside each descriptor
     */
    static List<String> writeDescriptors(List<PluginDefinition> definitions, Collection<File> configFiles, File outDir) {
        for (PluginDefinition definition : definitions) {
            File pluginDir = new File(outDir, PLUGIN_DESCRIPTORS_PREFIX + definition.pluginName)
            pluginDir.mkdirs()
            new File(pluginDir, PLUGIN_PROPERTIES_FILE).withWriter('UTF-8') { Writer writer -> definition.write(writer) }
            for (File configFile : configFiles) {
                if (configFile.isFile()) {
                    Files.copy(configFile.toPath(), new File(pluginDir, configFile.name).toPath(), StandardCopyOption.REPLACE_EXISTING)
                }
            }
        }
        List<String> names = definitions*.pluginName
        File importsFile = new File(outDir, PLUGINS_IMPORTS_PATH)
        importsFile.parentFile.mkdirs()
        importsFile.setText(([GENERATED_HEADER] + names).join('\n') + '\n', StandardCharsets.UTF_8.name())
        names
    }

    private static boolean isExcluded(String className, List<String> patterns) {
        if (!patterns) {
            return false
        }
        String path = className.replace('.' as char, '/' as char)
        patterns.any { String pattern -> antMatch(pattern, path) }
    }

    static boolean antMatch(String pattern, String path) {
        if (pattern == null || path == null) {
            return false
        }
        StringBuilder regex = new StringBuilder(pattern.length() * 2)
        int i = 0
        int len = pattern.length()
        while (i < len) {
            if (pattern.startsWith('**/', i)) {
                regex.append('(?:.*/)?')
                i += 3
            }
            else if (pattern.startsWith('**', i)) {
                regex.append('.*')
                i += 2
            }
            else {
                char ch = pattern.charAt(i)
                if (ch == ('*' as char)) {
                    regex.append('[^/]*')
                }
                else if (ch == ('?' as char)) {
                    regex.append('[^/]')
                }
                else if ('\\.^$+()[]{}|'.indexOf(ch as int) >= 0) {
                    regex.append('\\').append(ch)
                }
                else {
                    regex.append(ch)
                }
                i++
            }
        }
        path.matches(regex.toString())
    }

    private static final class ClassScanner extends ClassVisitor {

        private int access
        private boolean genericClass
        Map<String, Object> declaration
        String artefactType
        String autoConfiguration

        ClassScanner() {
            super(Opcodes.ASM9)
        }

        @Override
        void visit(int version, int access, String name, String signature, String superName, String[] interfaces) {
            this.access = access
            this.genericClass = signature != null && signature.startsWith('<')
        }

        boolean isConcrete() {
            (access & (Opcodes.ACC_ABSTRACT | Opcodes.ACC_INTERFACE | Opcodes.ACC_ANNOTATION |
                    Opcodes.ACC_ENUM | Opcodes.ACC_SYNTHETIC | Opcodes.ACC_MODULE)) == 0
        }

        boolean isProvidedArtefact() {
            artefactType != null && !genericClass
        }

        @Override
        AnnotationVisitor visitAnnotation(String descriptor, boolean visible) {
            if (PLUGIN_DESCRIPTOR_ANNOTATION == descriptor) {
                Map<String, Object> attributes = new LinkedHashMap<>()
                declaration = attributes
                return new AnnotationVisitor(Opcodes.ASM9) {
                    @Override
                    void visit(String name, Object value) {
                        attributes.put(name, value instanceof Type ? ((Type) value).className : value)
                    }

                    @Override
                    AnnotationVisitor visitArray(String name) {
                        List<String> values = []
                        attributes.put(name, values)
                        new AnnotationVisitor(Opcodes.ASM9) {
                            @Override
                            void visit(String ignored, Object value) {
                                String text = value instanceof Type ? ((Type) value).className : value?.toString()
                                if (text?.trim()) {
                                    values.add(text.trim())
                                }
                            }
                        }
                    }
                }
            }
            if (GRAILS_BEANS_ANNOTATION == descriptor) {
                return new AnnotationVisitor(Opcodes.ASM9) {
                    @Override
                    void visit(String name, Object value) {
                        if (AUTO_CONFIGURATION_NAME == name && value instanceof String) {
                            autoConfiguration = (String) value
                        }
                    }
                }
            }
            if (ARTEFACT_ANNOTATION == descriptor) {
                return new AnnotationVisitor(Opcodes.ASM9) {
                    @Override
                    void visit(String name, Object value) {
                        if ('value' == name && value instanceof String) {
                            artefactType = (String) value
                        }
                    }
                }
            }
            null
        }
    }
}

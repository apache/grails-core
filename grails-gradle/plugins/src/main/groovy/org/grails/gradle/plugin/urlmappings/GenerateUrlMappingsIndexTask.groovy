package org.grails.gradle.plugin.urlmappings

import groovy.transform.CompileStatic

import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.IgnoreEmptyDirectories
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.gradle.work.DisableCachingByDefault

/**
 * Writes the URL mapping index for this application or plugin.
 *
 * <p>URL mappings come from the application and from every plugin, so each project writes its own
 * {@code META-INF/grails/url-mappings.index} into its own classpath root. The runtime reads every
 * copy. The file is generated and is not configuration an application edits.</p>
 *
 * <p>The format is UTF-8 properties, version {@code 1}:</p>
 *
 * <pre><code>format.version=1
 * artifact.type=application
 * artifact.name=my-app
 * mapping.count=1
 * mapping.0.pattern=/books
 * mapping.0.controller=book
 * mapping.0.action=list</code></pre>
 *
 * <p>{@code mapping.N.method}, {@code mapping.N.namespace}, {@code mapping.N.plugin} and
 * {@code mapping.N.view} are written when the mapping states them. Characters outside ASCII are
 * {@code \\u} escapes, which {@code Properties.load} reads back.</p>
 *
 * @since 8.1
 */
@DisableCachingByDefault(because = 'Writing a handful of lines is cheaper than a build-cache round trip')
@CompileStatic
abstract class GenerateUrlMappingsIndexTask extends DefaultTask {

    /** Path of the generated index within the artifact. Matches the runtime reader. */
    static final String INDEX_PATH = 'META-INF/grails/url-mappings.index'

    static final String FORMAT_VERSION = '1'

    static final String TYPE_APPLICATION = 'application'

    static final String TYPE_PLUGIN = 'plugin'

    /**
     * The {@code *UrlMappings.groovy} sources in this project, normally under
     * {@code grails-app/controllers}.
     */
    @InputFiles
    @IgnoreEmptyDirectories
    @PathSensitive(PathSensitivity.RELATIVE)
    abstract ConfigurableFileCollection getSources()

    /** Either {@link #TYPE_APPLICATION} or {@link #TYPE_PLUGIN}. */
    @Input
    abstract Property<String> getArtifactType()

    /** The application or plugin name, recorded so the copies can be told apart. */
    @Input
    abstract Property<String> getArtifactName()

    /** Directory contributed to {@code processResources}; holds {@link #INDEX_PATH}. */
    @OutputDirectory
    abstract DirectoryProperty getOutputDirectory()

    @TaskAction
    void generate() {
        File index = outputDirectory.get().file(INDEX_PATH).asFile
        List<File> files = new ArrayList<>(sources.files)
        List<UrlMappingsSourceIndex.Mapping> mappings = []
        for (File source : files) {
            try {
                mappings.addAll(UrlMappingsSourceIndex.read(Collections.singletonList(source)))
            }
            catch (Exception ex) {
                // A source this parser cannot read is left to runtime evaluation. Failing the build
                // would make an optional index mandatory.
                getLogger().warn('URL mapping index: could not read ' + source.getName() +
                        '; those mappings stay runtime-only', ex)
            }
        }
        mappings = UrlMappingsSourceIndex.ordered(mappings)
        index.parentFile.mkdirs()
        StringBuilder text = new StringBuilder()
        text.append('# Generated by the Grails Gradle plugin. Do not edit.').append('\n')
        text.append('format.version=').append(FORMAT_VERSION).append('\n')
        text.append('artifact.type=').append(escape(artifactType.get())).append('\n')
        text.append('artifact.name=').append(escape(artifactName.get())).append('\n')
        text.append('mapping.count=').append(mappings.size()).append('\n')
        for (int i = 0; i < mappings.size(); i++) {
            UrlMappingsSourceIndex.Mapping mapping = mappings.get(i)
            String prefix = 'mapping.' + i + '.'
            append(text, prefix + 'pattern', mapping.pattern)
            append(text, prefix + 'controller', mapping.controller)
            append(text, prefix + 'action', mapping.action)
            append(text, prefix + 'method', mapping.httpMethod)
            append(text, prefix + 'namespace', mapping.namespace)
            append(text, prefix + 'plugin', mapping.plugin)
            append(text, prefix + 'view', mapping.view)
        }
        index.setText(text.toString(), 'UTF-8')
    }

    private static void append(StringBuilder text, String key, String value) {
        if (value != null && !value.isEmpty()) {
            text.append(key).append('=').append(escape(value)).append('\n')
        }
    }

    private static String escape(String value) {
        StringBuilder out = new StringBuilder(value.length())
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i)
            if (c == '\\') {
                out.append('\\\\')
            }
            else if (c == '\n') {
                out.append('\\n')
            }
            else if (c == '\r') {
                out.append('\\r')
            }
            else if (c == '\t') {
                out.append('\\t')
            }
            else if (c < 0x20 || c > 0x7E) {
                out.append(String.format('\\u%04x', (int) c))
            }
            else {
                out.append(c)
            }
        }
        return out.toString()
    }
}
